/// Orientación física utilizada por la captura sin depender de Flutter.
enum VisionDeviceOrientation {
  /// Dispositivo vertical con la parte superior hacia arriba.
  portraitUp,

  /// Dispositivo horizontal con la parte superior hacia la izquierda.
  landscapeLeft,

  /// Dispositivo vertical invertido.
  portraitDown,

  /// Dispositivo horizontal con la parte superior hacia la derecha.
  landscapeRight,
}
